public class Iteration_loop {
    public static void main(String[] args) {
        //loops---> while loop,do-while loop,for loop
        //while loop ->
        int i=1;
        while (i<=10) {
            System.out.println(i);
            i++;
            
        }
        //do-while loop ->
        int a=1;
        do{
            System.out.println(a);
            a++;
        }while(a<=10);
    //for loop ->
    int tabel=2;
    for(int c=1; c<=10; c++){
        System.out.println("Table of 2->"+tabel*c);
    }

    }

    
}
